"""Static HTML dashboard (Jinja2, autoescaped) plus a machine-readable summary.json.

The site is regenerated by every pipeline run and published to GitHub Pages by
.github/workflows/pages.yml. A banner states whether the data is live (and from
where, with acknowledgement) or demo data.
"""

from __future__ import annotations

import json
import os
from collections.abc import Sequence
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from jinja2 import Environment, PackageLoader, select_autoescape

from bidalert import __version__
from bidalert.models import ScreenedTender
from bidalert.processing.deadlines import IST, closing_bucket, days_remaining
from bidalert.profile import FACTORS, CompanyProfile

FACTOR_LABELS = {
    "category": "Category match",
    "state": "State preference",
    "msme": "MSME advantage",
    "value": "Value band",
    "deadline": "Deadline comfort",
}
BUCKET_LABELS = {
    "closing_24h": "within 24 hours",
    "closing_3d": "within 3 days",
    "closing_7d": "within 7 days",
    "later": "more than 7 days",
}


def _fmt_ist(dt: datetime | None) -> str:
    return dt.astimezone(IST).strftime("%d %b %Y, %H:%M IST") if dt else ""


def _row(rank: int, s: ScreenedTender, now: datetime) -> dict[str, Any]:
    t = s.tender
    factors = []
    for f in s.score.factors if s.score else ():
        factors.append(
            {
                "name": f.name,
                "label": FACTOR_LABELS[f.name],
                "weight": f.weight,
                "value": f.value,
                "contribution": f.contribution,
                "known": f.known,
                "reason": f.reason,
                "pct": round(f.contribution * 100, 2),
            }
        )
    return {
        "rank": rank,
        "title": t.title,
        "organisation": t.organisation,
        "portal": t.portal,
        "tender_id": t.source_tender_id,
        "reference_no": t.reference_no,
        "url": t.url,
        "closing": _fmt_ist(t.closing_at),
        "days_left": round(days_remaining(t.closing_at, now), 1),
        "bucket": BUCKET_LABELS.get(closing_bucket(t.closing_at, now), ""),
        "score": s.score.total if s.score else 0.0,
        "tier": s.score.tier if s.score else "",
        "category": s.category,
        "keywords": list(s.matched_keywords),
        "unverified": list(s.eligibility.unverified) if s.eligibility else [],
        "factors": factors,
    }


def _bars(items: Sequence[tuple[str, int]]) -> list[dict[str, Any]]:
    top = max((n for _, n in items), default=0) or 1
    return [{"label": k, "count": n, "pct": round(100 * n / top, 1)} for k, n in items]


def build_context(result: Any, profile: CompanyProfile) -> dict[str, Any]:
    now: datetime = result.now
    shortlist = [_row(i, s, now) for i, s in enumerate(result.shortlist, start=1)]
    funnel = _bars(
        [
            ("Fetched from sources", len(result.screened)),
            ("Unique after dedup", len(result.unique)),
            ("Passed eligibility filters", len(result.eligible)),
            ("High or medium priority", len(result.tier("high")) + len(result.tier("medium"))),
        ]
    )
    buckets = result.closing_buckets()
    live_sources = [r for r in result.sources if r.is_live and r.ok and r.fetched]
    server = os.environ.get("GITHUB_SERVER_URL")
    repo = os.environ.get("GITHUB_REPOSITORY")
    run_id = os.environ.get("GITHUB_RUN_ID")
    duration = (
        (result.finished_at - result.started_at).total_seconds() if result.finished_at else None
    )
    return {
        "version": __version__,
        "generated_at": _fmt_ist(result.finished_at or datetime.now(UTC)),
        "screened_as_of": _fmt_ist(now),
        "live": result.live,
        "live_sources": live_sources,
        "sources": result.sources,
        "profile": profile,
        "kpis": {
            "fetched": len(result.screened),
            "duplicates": len(result.duplicates),
            "unique": len(result.unique),
            "ineligible": len(result.ineligible),
            "eligible": len(result.eligible),
            "high": len(result.tier("high")),
            "medium": len(result.tier("medium")),
            "low": len(result.tier("low")),
        },
        "funnel": funnel,
        "reasons": _bars(result.reason_counts().most_common()),
        "keywords": _bars(result.keyword_counts().most_common(10)),
        "buckets": [(BUCKET_LABELS[k], buckets.get(k, 0)) for k in BUCKET_LABELS],
        "shortlist": shortlist,
        "factors": [(f, FACTOR_LABELS[f], profile.weights[f]) for f in FACTORS],
        "duplicates": [
            {
                "title": s.tender.title,
                "portal": s.tender.portal,
                "of": s.duplicate_of,
                "similarity": s.duplicate_similarity,
            }
            for s in result.duplicates[:8]
        ],
        "peak": result.peak_concurrent_bids,
        "peak_at": _fmt_ist(result.peak_at),
        "duration_s": round(duration, 1) if duration is not None else None,
        "commit": (os.environ.get("GITHUB_SHA") or "")[:7],
        "run_url": f"{server}/{repo}/actions/runs/{run_id}" if server and repo and run_id else None,
    }


def write_site(result: Any, profile: CompanyProfile, site_dir: Path) -> Path:
    env = Environment(
        loader=PackageLoader("bidalert", "templates"),
        autoescape=select_autoescape(["html", "j2"]),
        trim_blocks=True,
        lstrip_blocks=True,
    )
    ctx = build_context(result, profile)
    site_dir.mkdir(parents=True, exist_ok=True)
    out = site_dir / "index.html"
    out.write_text(env.get_template("dashboard.html.j2").render(**ctx), encoding="utf-8")
    summary = {
        "generated_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "screened_as_of": result.now.isoformat(timespec="seconds"),
        "live": result.live,
        "stats": result.stats(),
    }
    (site_dir / "summary.json").write_text(
        json.dumps(summary, indent=2, default=str), encoding="utf-8"
    )
    (site_dir / ".nojekyll").write_text("", encoding="utf-8")
    return out
