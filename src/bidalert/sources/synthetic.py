def _variant(title: str, rng: random.Random) -> str:
    """Cosmetic re-listing of the same tender, as another portal would show it."""
    choice = rng.randrange(3)
    if choice == 0:
        return title.upper()
    if choice == 1:
        return title.replace(" - ", ": ").replace("Supply of", "Procurement of supply of")
    return title + " (re-published)"


class SyntheticAdapter(SourceAdapter):
    name = "synthetic"
    is_live = False
    description = (
        "SYNTHETIC demo tenders generated by bidalert.sources.synthetic (seeded); not real listings"
    )

    def __init__(
        self, n: int = 160, seed: int = 42, now: datetime | None = None, duplicate_rate: float = 0.1
    ) -> None:
        self.n = n
        self.seed = seed
        self.now = now
        self.duplicate_rate = duplicate_rate

    def fetch(self) -> Iterator[Tender]:
        rng = random.Random(self.seed)
        now = (
            (self.now or datetime.now(IST))
            .astimezone(IST)
            .replace(minute=0, second=0, microsecond=0)
        )
        categories = list(ITEMS)
        for i in range(self.n):
            portal = rng.choice(PORTALS)
            dept = rng.choice(DEPARTMENTS)
            state = rng.choice(STATES)
            if rng.random() < 0.08:
                category = "Civil Works"
                title = f"{rng.choice(WORKS)} - {dept}, {state}"
            else:
                category = rng.choice(categories)
                title = f"Supply of {rng.choice(ITEMS[category])} - {dept}, {state}"
            published = now - timedelta(days=rng.randint(0, 20), hours=rng.randint(0, 23))
            closing = now + timedelta(days=rng.randint(1, 45), hours=rng.randint(9, 17) - now.hour)
            tender = Tender(
                source=self.name,
                source_tender_id=f"SYN-{portal[:3].upper()}-{i + 1:04d}",
                portal=portal,
                title=title,
                organisation=dept,
                published_at=published,
                closing_at=closing,
                category=category,
                state=state,
                estimated_value_inr=round(rng.lognormvariate(13.5, 1.2)),
                turnover_requirement_cr=round(rng.uniform(0.5, 5.0), 1),
                experience_years_required=rng.randint(1, 7),
                msme_preferred=rng.random() < 1 / 3,
                is_synthetic=True,
            )
            yield tender
            if rng.random() < self.duplicate_rate:
                other = rng.choice([p for p in PORTALS if p != portal])
                yield Tender(
                    **{
                        **tender.__dict__,
                        "source_tender_id": f"SYN-{other[:3].upper()}-{i + 1:04d}D",
                        "portal": other,
                        "title": _variant(title, rng),
                        "raw": {"synthetic_duplicate_of": tender.source_tender_id},
                    }
                )
